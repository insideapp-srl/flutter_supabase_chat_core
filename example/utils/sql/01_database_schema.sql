-- ============================================================================
-- chats schema setup (v2, flutter_chat_core based)
--
-- This script is idempotent and self-detecting: it bootstraps a fresh
-- database, or migrates the original v1 (flutter_chat_types) schema to v2,
-- from the same file. Re-running it on an already up-to-date database is a
-- no-op. Adjust the "chats" schema name below if you used a custom
-- SupabaseChatCoreConfig.schema.
--
-- Only two prior shapes are recognized: no chats.rooms at all (fresh
-- install), or the exact v1 shape this package ever shipped (bigint ids,
-- epoch-ms bigint dates, chats.rooms."userIds" uuid[]/"userRoles" jsonb,
-- chats.messages' old flutter_chat_types columns). If your database is
-- instead in some other, partially-migrated shape (e.g. from an earlier
-- draft of this script), reconcile or drop+recreate the chats schema
-- yourself before running this — it is not handled here.
--
-- v2 shape:
--   - chats.rooms.id / chats.messages.id / chats.messages."roomId": uuid,
--     default chats.uuid_generate_v7() (time-ordered — see below). Either
--     generated by the database or supplied by the client (e.g. for
--     optimistic UI: SupabaseChatController.sendMessage inserts locally with
--     a client-generated id, which Realtime then echoes back unchanged).
--     chats.users.id is untouched: it must keep matching auth.users.id.
--   - "createdAt"/"updatedAt"/"lastSeen" are timestamptz, not epoch-ms
--     bigint.
--   - Room membership lives in chats.room_members (roomId, userId FKs),
--     not a chats.rooms."userIds" uuid[]/"userRoles" jsonb pair. A room is
--     deleted automatically once its last member is removed. "role" is
--     constrained by a CHECK constraint (not a native enum: adding an
--     allowed value later is a plain DROP+ADD CONSTRAINT, no ALTER TYPE).
--   - chats.messages is a native RANGE partition on "createdAt", managed by
--     pg_partman with weekly partitions and no automatic retention (chat
--     history is kept forever — partitioning is purely for keeping
--     indexes/vacuum/queries scalable as history grows).
--   - Deleting a message removes the row immediately; if it referenced a
--     chats_assets storage object, the object's path is recorded in
--     chats.media_pending_deletion for a separate cleanup job (a Deno Edge
--     Function, see supabase/functions/cleanup-media) to remove later — SQL
--     alone can't delete objects from the storage backend.
--
-- A v1 migration renames each old table to a `..._backup_<timestamp>` table
-- and keeps it (never drops it) rather than rebuilding in place; verify row
-- counts, then drop them yourself once satisfied (oldest-dependency-first:
-- messages_backup_* before rooms_backup_*/users_backup_*, since the old
-- messages_roomId_fkey/messages_authorId_fkey constraints still point at
-- them). See MIGRATION.md for the full writeup, including the separate
-- storage-object move needed after a uuid conversion
-- (example/utils/migrate_storage_uuids.sh/.ps1).
--
-- Run a migration during a maintenance window: the app must be compatible
-- with the resulting shape before it runs against this database again.
--
-- Requires the pg_partman and pg_cron extensions available (both ship in
-- Supabase's self-hosted Postgres image). pg_cron jobs run against the
-- database it's installed in — on Supabase self-hosted that's normally the
-- `postgres` database already, no extra setup needed there.
-- ============================================================================

CREATE SCHEMA IF NOT EXISTS chats;
ALTER SCHEMA chats OWNER TO postgres;

SET default_tablespace = '';
SET default_table_access_method = heap;

-- pg_partman gets its own schema so its catalog/maintenance tables aren't
-- exposed to anon/authenticated via the blanket `GRANT ALL ... IN SCHEMA
-- chats` below. `CREATE EXTENSION ... SCHEMA partman` does NOT create that
-- schema for you -- it must already exist, or the extension creation fails.
CREATE SCHEMA IF NOT EXISTS partman;
CREATE EXTENSION IF NOT EXISTS pg_partman SCHEMA partman;
CREATE EXTENSION IF NOT EXISTS pg_cron;

-- Time-ordered UUIDs (RFC 9562 UUIDv7): the id generator for chats.rooms and
-- chats.messages instead of a fully random UUIDv4, so ids stay roughly
-- sequential (like the old bigint identities) and don't fragment each
-- partition's primary key index the way random UUIDs would. Native
-- uuidv7() ships starting with Postgres 18; this works on any version
-- Supabase currently ships, no extra extension required.
CREATE OR REPLACE FUNCTION chats.uuid_generate_v7()
RETURNS uuid
LANGUAGE sql
VOLATILE
AS $$
    SELECT encode(
        set_bit(
            set_bit(
                overlay(uuid_send(gen_random_uuid()) placing
                    substring(int8send(floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint) from 3)
                    from 1 for 6
                ),
                52, 1
            ),
            53, 1
        ),
        'hex'
    )::uuid;
$$;

-- Enabling row level security on a partitioned table only recurses to the
-- partitions that already exist at that moment -- it does NOT retroactively
-- apply to partitions created afterwards (unlike indexes and row-level
-- triggers, which Postgres does propagate automatically). pg_partman keeps
-- creating new chats.messages partitions on its own schedule, so this is
-- called both right after creating partitions and from the hourly pg_cron
-- maintenance job below, to catch any partition RLS wasn't enabled on yet.
CREATE OR REPLACE FUNCTION chats.ensure_messages_partitions_rls()
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    r record;
BEGIN
    FOR r IN
        SELECT c.oid::regclass AS partition
        FROM pg_inherits i
        JOIN pg_class c ON c.oid = i.inhrelid
        WHERE i.inhparent = 'chats.messages'::regclass
          AND NOT c.relrowsecurity
    LOOP
        EXECUTE format('ALTER TABLE %s ENABLE ROW LEVEL SECURITY', r.partition);
    END LOOP;
END;
$$;

DO $do$
DECLARE
    v_ts text := extract(epoch FROM clock_timestamp())::bigint::text;
    v_is_fresh boolean;
    v_is_v1 boolean := false;
    v_start_ts timestamptz;
    v_rooms_backup text;
    v_users_backup text;
    v_messages_backup text;
    v_needs_partman boolean := false;
BEGIN
    SELECT NOT EXISTS (
        SELECT 1 FROM information_schema.tables
        WHERE table_schema = 'chats' AND table_name = 'rooms'
    ) INTO v_is_fresh;

    IF NOT v_is_fresh THEN
        SELECT (data_type <> 'uuid') INTO v_is_v1
        FROM information_schema.columns
        WHERE table_schema = 'chats' AND table_name = 'rooms' AND column_name = 'id';
    END IF;

    -- ========================================================================
    -- chats.users / chats.rooms
    -- ========================================================================
    IF v_is_fresh THEN
        RAISE NOTICE 'Fresh install: creating chats.users and chats.rooms directly in v2 shape';

        CREATE TABLE chats.users (
            "firstName" text,
            "imageUrl" text,
            "lastName" text,
            metadata jsonb,
            role text,
            id uuid NOT NULL,
            "createdAt" timestamptz NOT NULL DEFAULT now(),
            "updatedAt" timestamptz NOT NULL DEFAULT now(),
            "lastSeen" timestamptz NOT NULL DEFAULT now()
        );
        ALTER TABLE chats.users OWNER TO postgres;
        ALTER TABLE ONLY chats.users ADD CONSTRAINT users_pkey PRIMARY KEY (id);
        ALTER TABLE ONLY chats.users
            ADD CONSTRAINT users_id_fkey FOREIGN KEY (id) REFERENCES auth.users(id) ON UPDATE CASCADE ON DELETE CASCADE;
        ALTER TABLE chats.users ENABLE ROW LEVEL SECURITY;
        ALTER PUBLICATION supabase_realtime ADD TABLE ONLY chats.users;

        CREATE TABLE chats.rooms (
            id uuid NOT NULL DEFAULT chats.uuid_generate_v7(),
            "imageUrl" text,
            metadata jsonb,
            name text,
            type text,
            "lastMessages" jsonb,
            "createdAt" timestamptz NOT NULL DEFAULT now(),
            "updatedAt" timestamptz NOT NULL DEFAULT now()
        );
        ALTER TABLE chats.rooms OWNER TO postgres;
        ALTER TABLE ONLY chats.rooms ADD CONSTRAINT rooms_pkey PRIMARY KEY (id);
        ALTER TABLE chats.rooms ENABLE ROW LEVEL SECURITY;
        ALTER PUBLICATION supabase_realtime ADD TABLE ONLY chats.rooms;

    ELSIF v_is_v1 THEN
        RAISE NOTICE 'v1 schema detected (chats.rooms.id is bigint): migrating users and rooms to v2 shape';

        -- Maps each old bigint room id to its freshly generated uuid, built
        -- before anything is renamed away. Reused below for room_members and
        -- chats.messages."roomId". Kept around (not temporary) after this
        -- script finishes: storage objects under `chats_assets/<old room
        -- id>/...` still need moving to `chats_assets/<new room id>/...` (a
        -- separate step -- SQL alone can't rename objects in the storage
        -- backend). See example/utils/migrate_storage_uuids.sh/.ps1 and
        -- MIGRATION.md.
        CREATE TABLE IF NOT EXISTS chats.room_id_migration_map (
            old_id bigint PRIMARY KEY,
            new_id uuid NOT NULL
        );
        INSERT INTO chats.room_id_migration_map (old_id, new_id)
        SELECT id, chats.uuid_generate_v7() FROM chats.rooms;

        -- --- chats.users: rename away, recreate in final shape, copy back ---
        -- Done BEFORE chats.room_members is created below: room_members has
        -- a real FK to chats.users(id), and Postgres binds foreign keys to
        -- the referenced table by OID, not by name. Creating room_members
        -- against a chats.users that's about to be renamed away would leave
        -- its FK permanently pointing at the renamed backup table.
        v_users_backup := 'users_backup_' || v_ts;
        EXECUTE format('ALTER TABLE chats.users RENAME TO %I', v_users_backup);
        -- RENAME TABLE doesn't rename its constraints/indexes -- without
        -- this, the new chats.users below can't reuse the "users_pkey" name
        -- (index/constraint names are unique per schema, not per table).
        EXECUTE format('ALTER TABLE chats.%I RENAME CONSTRAINT users_pkey TO %I', v_users_backup, v_users_backup || '_pkey');

        CREATE TABLE chats.users (
            "firstName" text,
            "imageUrl" text,
            "lastName" text,
            metadata jsonb,
            role text,
            id uuid NOT NULL,
            "createdAt" timestamptz NOT NULL DEFAULT now(),
            "updatedAt" timestamptz NOT NULL DEFAULT now(),
            "lastSeen" timestamptz NOT NULL DEFAULT now()
        );
        ALTER TABLE chats.users OWNER TO postgres;
        ALTER TABLE ONLY chats.users ADD CONSTRAINT users_pkey PRIMARY KEY (id);
        ALTER TABLE ONLY chats.users
            ADD CONSTRAINT users_id_fkey FOREIGN KEY (id) REFERENCES auth.users(id) ON UPDATE CASCADE ON DELETE CASCADE;
        ALTER TABLE chats.users ENABLE ROW LEVEL SECURITY;

        EXECUTE format($f$
            INSERT INTO chats.users ("firstName", "imageUrl", "lastName", metadata, role, id, "createdAt", "updatedAt", "lastSeen")
            SELECT "firstName", "imageUrl", "lastName", metadata, role, id,
                   to_timestamp("createdAt" / 1000.0), to_timestamp("updatedAt" / 1000.0), to_timestamp("lastSeen" / 1000.0)
            FROM chats.%I
        $f$, v_users_backup);

        -- Publication membership follows the rename onto the backup table
        -- (tracked by relation, not by name) -- move it back onto the new
        -- chats.users.
        IF EXISTS (
            SELECT 1 FROM pg_publication_tables
            WHERE pubname = 'supabase_realtime' AND schemaname = 'chats' AND tablename = v_users_backup
        ) THEN
            EXECUTE format('ALTER PUBLICATION supabase_realtime DROP TABLE chats.%I', v_users_backup);
        END IF;
        ALTER PUBLICATION supabase_realtime ADD TABLE ONLY chats.users;

        RAISE NOTICE 'chats.% kept as a backup — verify row counts match, then drop it yourself once satisfied.', v_users_backup;

        -- --- chats.rooms: rename away, recreate in final shape, copy back ---
        v_rooms_backup := 'rooms_backup_' || v_ts;
        EXECUTE format('ALTER TABLE chats.rooms RENAME TO %I', v_rooms_backup);
        EXECUTE format('ALTER TABLE chats.%I RENAME CONSTRAINT rooms_pkey TO %I', v_rooms_backup, v_rooms_backup || '_pkey');

        CREATE TABLE chats.rooms (
            id uuid NOT NULL DEFAULT chats.uuid_generate_v7(),
            "imageUrl" text,
            metadata jsonb,
            name text,
            type text,
            "lastMessages" jsonb,
            "createdAt" timestamptz NOT NULL DEFAULT now(),
            "updatedAt" timestamptz NOT NULL DEFAULT now()
        );
        ALTER TABLE chats.rooms OWNER TO postgres;
        ALTER TABLE ONLY chats.rooms ADD CONSTRAINT rooms_pkey PRIMARY KEY (id);
        ALTER TABLE chats.rooms ENABLE ROW LEVEL SECURITY;

        EXECUTE format($f$
            INSERT INTO chats.rooms (id, "imageUrl", metadata, name, type, "lastMessages", "createdAt", "updatedAt")
            SELECT m.new_id, r."imageUrl", r.metadata, r.name, r.type, r."lastMessages",
                   to_timestamp(r."createdAt" / 1000.0), to_timestamp(r."updatedAt" / 1000.0)
            FROM chats.%I r
            JOIN chats.room_id_migration_map m ON m.old_id = r.id
        $f$, v_rooms_backup);

        IF EXISTS (
            SELECT 1 FROM pg_publication_tables
            WHERE pubname = 'supabase_realtime' AND schemaname = 'chats' AND tablename = v_rooms_backup
        ) THEN
            EXECUTE format('ALTER PUBLICATION supabase_realtime DROP TABLE chats.%I', v_rooms_backup);
        END IF;
        ALTER PUBLICATION supabase_realtime ADD TABLE ONLY chats.rooms;

        RAISE NOTICE 'chats.% kept as a backup — verify row counts match, then drop it yourself once satisfied.', v_rooms_backup;
    ELSE
        RAISE NOTICE 'chats.users/chats.rooms already at v2 shape: nothing to do';
    END IF;

    -- ========================================================================
    -- chats.room_members
    --
    -- Only created here: under the two shapes this script recognizes (fresh
    -- install, or exact v1), it never already exists beforehand. Created
    -- only after chats.users and chats.rooms above have reached their final
    -- v2 shape, so its foreign keys always bind to the real tables.
    -- ========================================================================
    IF v_is_fresh OR v_is_v1 THEN
        RAISE NOTICE 'Creating chats.room_members';

        CREATE TABLE chats.room_members (
            "roomId" uuid NOT NULL REFERENCES chats.rooms(id) ON DELETE CASCADE,
            "userId" uuid NOT NULL REFERENCES chats.users(id) ON DELETE CASCADE,
            role text,
            "createdAt" timestamptz NOT NULL DEFAULT now(),
            PRIMARY KEY ("roomId", "userId")
        );
        ALTER TABLE chats.room_members OWNER TO postgres;
        ALTER TABLE chats.room_members ENABLE ROW LEVEL SECURITY;
        ALTER PUBLICATION supabase_realtime ADD TABLE ONLY chats.room_members;

        IF v_is_v1 THEN
            RAISE NOTICE 'Populating chats.room_members from chats.%''s userIds/userRoles', v_rooms_backup;
            EXECUTE format($f$
                INSERT INTO chats.room_members ("roomId", "userId", role)
                SELECT m.new_id, u, r."userRoles" ->> u::text
                FROM chats.%I r
                JOIN chats.room_id_migration_map m ON m.old_id = r.id,
                     unnest(r."userIds") AS u
                ON CONFLICT ("roomId", "userId") DO NOTHING
            $f$, v_rooms_backup);
        END IF;
    END IF;

    -- Constrain role to the values ChatRoomRole knows about (NULL = plain
    -- member/user, no elevated role). A CHECK constraint rather than a
    -- native enum: adding an allowed value later is a plain DROP+ADD
    -- CONSTRAINT, no ALTER TYPE / no risk of a value already committed to
    -- production rows before the type change lands.
    ALTER TABLE chats.users DROP CONSTRAINT IF EXISTS users_role_check;
    ALTER TABLE chats.users ADD CONSTRAINT users_role_check CHECK (role IN ('admin', 'moderator'));
    ALTER TABLE chats.room_members DROP CONSTRAINT IF EXISTS room_members_role_check;
    ALTER TABLE chats.room_members ADD CONSTRAINT room_members_role_check CHECK (role IN ('admin', 'moderator'));

    -- ========================================================================
    -- chats.messages
    -- ========================================================================
    IF v_is_fresh THEN
        RAISE NOTICE 'Creating chats.messages (fresh install, partitioned + uuid + timestamptz from the start)';

        -- Column names match flutter_chat_core's v2 Message model field
        -- names directly (source, waveform, linkPreviewData,
        -- replyToMessageId, ...).
        CREATE TABLE chats.messages (
            id uuid NOT NULL DEFAULT chats.uuid_generate_v7(),
            "createdAt" timestamptz NOT NULL DEFAULT now(),
            metadata jsonb,
            duration bigint,
            "mimeType" text,
            name text,
            "replyToMessageId" text,
            "roomId" uuid NOT NULL,
            size bigint,
            status text,
            type text,
            "updatedAt" timestamptz,
            source text,
            waveform jsonb,
            height double precision,
            width double precision,
            "linkPreviewData" jsonb,
            "authorId" uuid NOT NULL,
            text text,
            reactions jsonb,
            pinned boolean
        ) PARTITION BY RANGE ("createdAt");

        ALTER TABLE chats.messages OWNER TO postgres;

        -- "id" alone can no longer be the primary key: native partitioning
        -- requires the partition key ("createdAt") to be part of every
        -- unique/primary key index. Nothing else references messages.id via
        -- foreign key, so this is safe.
        ALTER TABLE ONLY chats.messages ADD CONSTRAINT messages_pkey PRIMARY KEY (id, "createdAt");

        -- No "ONLY": Postgres rejects it for a foreign key added on a
        -- partitioned table ("cannot use ONLY for foreign key on
        -- partitioned table") — the constraint must apply to the whole
        -- partition hierarchy anyway.
        ALTER TABLE chats.messages
            ADD CONSTRAINT "messages_authorId_fkey" FOREIGN KEY ("authorId") REFERENCES auth.users(id) ON DELETE CASCADE;

        ALTER TABLE chats.messages
            ADD CONSTRAINT "messages_roomId_fkey" FOREIGN KEY ("roomId") REFERENCES chats.rooms(id) ON UPDATE CASCADE ON DELETE CASCADE;

        CREATE INDEX ON chats.messages USING btree ("authorId");
        CREATE INDEX ON chats.messages USING btree ("roomId");

        ALTER TABLE chats.messages ENABLE ROW LEVEL SECURITY;
        ALTER PUBLICATION supabase_realtime ADD TABLE chats.messages;

        v_needs_partman := true;

    ELSIF v_is_v1 THEN
        RAISE NOTICE 'Migrating chats.messages (v1 columns, bigint id, epoch-ms dates) to v2 shape';

        -- v1 (flutter_chat_types) column renames, done in place before the
        -- rebuild below so the copy-back SELECT can just name the v2 columns
        -- directly.
        ALTER TABLE chats.messages RENAME COLUMN uri TO source;
        ALTER TABLE chats.messages RENAME COLUMN "waveForm" TO waveform;
        ALTER TABLE chats.messages RENAME COLUMN "previewData" TO "linkPreviewData";

        ALTER TABLE chats.messages ADD COLUMN IF NOT EXISTS "replyToMessageId" text;
        UPDATE chats.messages
        SET "replyToMessageId" = "repliedMessage" ->> 'id'
        WHERE "repliedMessage" IS NOT NULL
          AND "replyToMessageId" IS NULL;

        ALTER TABLE chats.messages ADD COLUMN IF NOT EXISTS reactions jsonb;
        ALTER TABLE chats.messages ADD COLUMN IF NOT EXISTS pinned boolean;

        -- "remoteId", "isLoading", "showStatus" and "repliedMessage" have no
        -- v2 equivalent and are left in place, unused, on the backup table
        -- created below (never on the final chats.messages) — nothing to
        -- drop here.

        SELECT to_timestamp(MIN("createdAt") / 1000.0) INTO v_start_ts FROM chats.messages;

        -- Can't ALTER this table into the partitioned/uuid/timestamptz shape
        -- in place: rename it out of the way, create the new table, then
        -- copy the data back in below.
        v_messages_backup := 'messages_backup_' || v_ts;
        EXECUTE format('ALTER TABLE chats.messages RENAME TO %I', v_messages_backup);
        EXECUTE format('ALTER TABLE chats.%I RENAME CONSTRAINT messages_pkey TO %I', v_messages_backup, v_messages_backup || '_pkey');

        CREATE TABLE chats.messages (
            id uuid NOT NULL DEFAULT chats.uuid_generate_v7(),
            "createdAt" timestamptz NOT NULL DEFAULT now(),
            metadata jsonb,
            duration bigint,
            "mimeType" text,
            name text,
            "replyToMessageId" text,
            "roomId" uuid NOT NULL,
            size bigint,
            status text,
            type text,
            "updatedAt" timestamptz,
            source text,
            waveform jsonb,
            height double precision,
            width double precision,
            "linkPreviewData" jsonb,
            "authorId" uuid NOT NULL,
            text text,
            reactions jsonb,
            pinned boolean
        ) PARTITION BY RANGE ("createdAt");

        ALTER TABLE chats.messages OWNER TO postgres;

        ALTER TABLE ONLY chats.messages ADD CONSTRAINT messages_pkey PRIMARY KEY (id, "createdAt");

        ALTER TABLE chats.messages
            ADD CONSTRAINT "messages_authorId_fkey" FOREIGN KEY ("authorId") REFERENCES auth.users(id) ON DELETE CASCADE;

        ALTER TABLE chats.messages
            ADD CONSTRAINT "messages_roomId_fkey" FOREIGN KEY ("roomId") REFERENCES chats.rooms(id) ON UPDATE CASCADE ON DELETE CASCADE;

        CREATE INDEX ON chats.messages USING btree ("authorId");
        CREATE INDEX ON chats.messages USING btree ("roomId");

        ALTER TABLE chats.messages ENABLE ROW LEVEL SECURITY;

        v_needs_partman := true;
    ELSE
        RAISE NOTICE 'chats.messages already at v2 shape: nothing to do';
    END IF;

    IF v_needs_partman THEN
        -- A rebuild (v1 migration) replaces the physical chats.messages
        -- table entirely, but pg_partman's own bookkeeping is keyed by table
        -- NAME, not by relation -- a stale partman.part_config row from a
        -- previous registration would make create_parent() below fail with a
        -- duplicate key error otherwise.
        DELETE FROM partman.part_config WHERE parent_table = 'chats.messages';

        -- Register with pg_partman before copying any old data back in, so
        -- weekly partitions already exist from the oldest message
        -- (p_start_partition) through p_premake weeks into the future.
        -- p_default_table (pg_partman's default) keeps a catch-all partition
        -- so no insert can ever fail even if a row's createdAt lands outside
        -- the generated range. "createdAt" is a native timestamptz now, so
        -- no p_epoch is needed (that was only for the old epoch-ms bigint).
        PERFORM partman.create_parent(
            p_parent_table => 'chats.messages',
            p_control => 'createdAt',
            p_interval => '7 days', -- weekly; recent pg_partman versions dropped the old 'weekly'/'monthly'/... shorthands in favor of plain Postgres interval literals
            p_premake => 4,
            p_start_partition => COALESCE(v_start_ts, now())::text
        );

        -- History is kept forever: partitioning here is for scalability
        -- (query/index/vacuum performance), not for expiring old messages.
        UPDATE partman.part_config
        SET retention = NULL,
            retention_keep_table = true,
            infinite_time_partitions = true
        WHERE parent_table = 'chats.messages';

        -- create_parent() just created the initial batch of partitions --
        -- none of them inherited chats.messages' RLS setting (see the note
        -- on ensure_messages_partitions_rls() above).
        PERFORM chats.ensure_messages_partitions_rls();
    END IF;

    IF v_messages_backup IS NOT NULL THEN
        EXECUTE format($f$
            INSERT INTO chats.messages (id, "createdAt", metadata, duration, "mimeType", name, "replyToMessageId", "roomId", size, status, type, "updatedAt", source, waveform, height, width, "linkPreviewData", "authorId", text, reactions, pinned)
            SELECT chats.uuid_generate_v7(), to_timestamp(m."createdAt" / 1000.0), m.metadata, m.duration, m."mimeType", m.name, m."replyToMessageId", rm.new_id, m.size, m.status, m.type,
                   CASE WHEN m."updatedAt" IS NULL THEN NULL ELSE to_timestamp(m."updatedAt" / 1000.0) END,
                   m.source, m.waveform, m.height, m.width, m."linkPreviewData", m."authorId", m.text, m.reactions, m.pinned
            FROM chats.%I m
            JOIN chats.room_id_migration_map rm ON rm.old_id = m."roomId"
        $f$, v_messages_backup);

        -- Publication membership followed the rename onto the backup table
        -- (tracked by relation, not by name) — move it back onto
        -- chats.messages, and add it WITHOUT "ONLY": a partitioned parent
        -- never holds rows itself, so Realtime must follow all of its
        -- (current and future) partitions instead.
        IF EXISTS (
            SELECT 1 FROM pg_publication_tables
            WHERE pubname = 'supabase_realtime' AND schemaname = 'chats' AND tablename = v_messages_backup
        ) THEN
            EXECUTE format('ALTER PUBLICATION supabase_realtime DROP TABLE chats.%I', v_messages_backup);
        END IF;
        ALTER PUBLICATION supabase_realtime ADD TABLE chats.messages;

        RAISE NOTICE 'chats.% kept as a backup of the pre-migration messages table — verify row counts match, then drop it yourself once satisfied.', v_messages_backup;
    END IF;

    -- ========================================================================
    -- chats.media_pending_deletion
    -- ========================================================================
    CREATE TABLE IF NOT EXISTS chats.media_pending_deletion (
        id uuid NOT NULL DEFAULT chats.uuid_generate_v7() PRIMARY KEY,
        "bucketId" text NOT NULL,
        path text NOT NULL,
        "createdAt" timestamptz NOT NULL DEFAULT now(),
        "processedAt" timestamptz
    );
    ALTER TABLE chats.media_pending_deletion OWNER TO postgres;
    -- No RLS policies defined on purpose: only the cleanup-media Edge
    -- Function (using the service_role key, which bypasses RLS) and this
    -- migration script need access. RLS is still enabled so enabling it
    -- isn't silently forgotten, and the blanket anon/authenticated grants
    -- below are revoked for this table specifically at the end of the file.
    ALTER TABLE chats.media_pending_deletion ENABLE ROW LEVEL SECURITY;
END
$do$;

-- Weekly-partition maintenance (pre-creating upcoming partitions). Runs
-- hourly via pg_cron; cheap/no-op when there's nothing due. No retention job
-- is scheduled — see the note above about keeping chat history forever.
DO $do$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'partman-run-maintenance') THEN
